const { _electron } = require('playwright-core')
const { mkdtempSync, mkdirSync, writeFileSync, readFileSync, rmSync } = require('node:fs')
const { tmpdir } = require('node:os')
const { join, resolve } = require('node:path')
const assert = require('node:assert/strict')
;(async()=>{
 const root=mkdtempSync(join(tmpdir(),'james-context-ui-')),userData=join(root,'void-jarvis')
 mkdirSync(join(userData,'skills'),{recursive:true})
 writeFileSync(join(userData,'settings.json'),JSON.stringify({setupDone:true,wake:{enabled:false,clap:false},automaticBackups:false}))
 writeFileSync(join(userData,'working-context.json'),JSON.stringify({goal:'Stream vorbereiten',decisions:['OBS lokal verwenden'],completed:['Szene geprüft'],next:['Mikrofon prüfen'],blockers:['Kamera fehlt'],status:'active',updatedAt:Date.now(),plan:{title:'Stream vorbereiten',steps:[{text:'Szene geprüft',status:'erledigt'},{text:'Mikrofon prüfen',status:'läuft'}],updatedAt:Date.now()}}))
 writeFileSync(join(userData,'skills','stream-vorbereiten.md'),'---\nname: Stream vorbereiten\ndescription: OBS für den Stream vorbereiten\nsource: manual\nuses: 2\nupdated: 2026-10-13\n---\n\n1. OBS öffnen.\n2. Mikrofon prüfen.\n')
 const wrapper=resolve('out/context-ui-wrapper.cjs')
 writeFileSync(wrapper,`const {app}=require('electron');app.setPath('appData',${JSON.stringify(root)});app.setPath('userData',${JSON.stringify(userData)});require('./main/index.js')`)
 let app
 try {
  app=await _electron.launch({executablePath:require('electron'),args:[wrapper,'--use-fake-device-for-media-stream','--use-fake-ui-for-media-stream']})
  await app.firstWindow();let page
  for(let i=0;i<100&&!page;i++){page=app.windows().find(p=>p.url().includes('crystal.html'));if(!page)await new Promise(r=>setTimeout(r,100))}
  assert.ok(page);await page.locator('.context-panel').waitFor()
  const errors=[];page.on('pageerror',e=>errors.push(e.message))
  let c=await page.evaluate(()=>window.jarvis.invoke('context:get'))
  assert.equal(c.status,'paused');assert.equal(c.plan.steps[1].status,'offen')
  assert.equal(await page.getByText('Zum Wiederaufnehmen',{exact:true}).count(),1)
  await page.evaluate(()=>{window.testTexts=[];const dispatch=window.dispatchEvent.bind(window);window.dispatchEvent=e=>{if(e.type==='jarvis:text'){window.testTexts.push(e.detail);return true}return dispatch(e)}})
  await page.getByRole('button',{name:'Aufgabe fortsetzen',exact:true}).click()
  assert.match(await page.evaluate(()=>window.testTexts.at(-1)),/gespeicherten Arbeitsstands/)
  await page.getByRole('button',{name:'Fertigkeiten',exact:true}).click()
  await page.locator('.skills-panel').waitFor()
  await page.getByLabel('Fertigkeiten suchen').fill('OBS')
  await page.locator('.skills-panel summary').filter({hasText:'Stream vorbereiten'}).click()
  await page.getByRole('button',{name:'Fertigkeit anwenden',exact:true}).click()
  assert.match(await page.evaluate(()=>window.testTexts.at(-1)),/gespeicherte Fertigkeit/)
  const result=await page.evaluate(()=>window.jarvis.invoke('tools:call',{id:crypto.randomUUID(),name:'context_checkpoint',args:{goal:'Stream vorbereiten',decisions:['OBS lokal verwenden'],completed:['Szene geprüft','Mikrofon geprüft'],next:['Stream starten'],blockers:[],status:'paused'}}))
  assert.equal(result.ok,true,result.error)
  assert.match(readFileSync(join(userData,'working-context.json'),'utf8'),/Mikrofon geprüft/)
  await page.evaluate(()=>window.jarvis.invoke('context:turn',{request:'Kontext-Testfrage 4711',answer:'Kontext-Testantwort 4711'}))
  const prompt=await page.evaluate(()=>window.jarvis.invoke('agent:systemPrompt',{query:'Stream'}))
  assert.match(prompt,/Mikrofon geprüft/);assert.match(prompt,/Kontext-Testantwort 4711/)
  await app.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows().find(w=>w.webContents.getURL().includes('crystal.html')).setSize(1000,900))
  await page.locator('.context-panel').scrollIntoViewIfNeeded()
  await page.screenshot({path:resolve('out/audit/context-hermes-ui.png')})
  await app.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows().find(w=>w.webContents.getURL().includes('crystal.html')).setSize(520,800))
  await page.screenshot({path:resolve('out/audit/context-hermes-ui-narrow.png')})
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false)
  await page.locator('.context-panel .answer-actions summary').click()
  await page.getByRole('button',{name:'Kontext und Verlauf löschen',exact:true}).click()
  await page.locator('.context-manage').waitFor()
  assert.equal((await page.evaluate(()=>window.jarvis.invoke('context:get'))).goal,'')
  const cleared=await page.evaluate(()=>window.jarvis.invoke('agent:systemPrompt'))
  assert.doesNotMatch(cleared,/Kontext-Testantwort 4711/)
  assert.equal((await page.evaluate(()=>window.jarvis.invoke('skills:list'))).length,1)
  assert.deepEqual(errors,[])
  console.log('PASS: paused restore, resume intent, skill library/search/apply, real checkpoint tool persistence, local conversation recall, clear without deleting skills, narrow layout, no renderer errors')
 }finally{if(app)await app.close();assert.ok(root.startsWith(join(tmpdir(),'james-context-ui-')));rmSync(root,{recursive:true,force:true})}
})().catch(e=>{console.error(e);process.exitCode=1})
