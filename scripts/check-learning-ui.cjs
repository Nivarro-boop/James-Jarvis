const { _electron } = require('playwright-core')
const { build } = require('esbuild')
const { mkdtempSync, mkdirSync, writeFileSync, readFileSync, existsSync, rmSync } = require('node:fs')
const { tmpdir } = require('node:os')
const { join, resolve } = require('node:path')
const assert = require('node:assert/strict')
;(async () => {
 const profile = mkdtempSync(join(tmpdir(), 'james-learning-ui-'))
 const userData = join(profile, 'void-jarvis'); mkdirSync(userData)
 writeFileSync(join(userData, 'settings.json'), JSON.stringify({ setupDone: true, wake: { enabled: false, clap: false }, automaticBackups: false }))
 await build({ entryPoints: ['src/main/agent/skillProposals.ts'], bundle: true, platform: 'node', format: 'cjs', packages: 'external', outfile: 'out/proposals-ui-test.cjs', alias: { '@shared': resolve('src/shared') }, plugins: [{ name: 'test-emitter', setup(b) { b.onLoad({ filter: /ipc[\\/]emit\.ts$/ }, () => ({ contents: `import { BrowserWindow } from 'electron'; export function broadcast(c,p){ for(const w of BrowserWindow.getAllWindows())w.webContents.send(c,p) }`, loader: 'ts' })) } }] })
 const wrapper = resolve('out/learning-ui-wrapper.cjs')
 writeFileSync(wrapper, `const {app,ipcMain}=require('electron');app.setPath('appData',${JSON.stringify(profile)});app.setPath('userData',${JSON.stringify(userData)});globalThis.learningTest=require('./proposals-ui-test.cjs');require('./main/index.js');app.whenReady().then(()=>{ipcMain.removeHandler('skills:decide');ipcMain.handle('skills:decide',(_e,p)=>globalThis.learningTest.decideSkill(p.id,p.accept))})`)
 let app
 try {
  app = await _electron.launch({ executablePath: require('electron'), args: [wrapper, '--use-fake-device-for-media-stream', '--use-fake-ui-for-media-stream'] })
  await app.firstWindow()
  let page
  for (let i=0;i<100&&!page;i++){ page=app.windows().find(p=>p.url().includes('crystal.html')); if(!page)await new Promise(r=>setTimeout(r,100)) }
  assert.ok(page); await page.locator('.home-bar').waitFor()
  const errors=[];page.on('pageerror',e=>errors.push(e.message))
  const propose=()=>app.evaluate(()=>globalThis.learningTest.proposeSkill({name:'Testablauf',description:'Wiederkehrenden Ablauf lernen',steps:'1. Ergebnis prüfen.\n2. Fertig melden.',source:'auto'}))
  await propose();await page.getByRole('heading',{name:'Testablauf'}).waitFor()
  assert.equal(existsSync(join(userData,'skills','testablauf.md')),false)
  await page.getByText('Vorschau ansehen',{exact:true}).click()
  await page.getByRole('button',{name:'Verwerfen',exact:true}).click()
  await page.getByRole('status').filter({hasText:'Vorschlag verworfen'}).waitFor()
  assert.equal(existsSync(join(userData,'skills','testablauf.md')),false)
  await propose();await page.getByRole('button',{name:'Übernehmen',exact:true}).click()
  await page.getByRole('status').filter({hasText:'übernommen'}).waitFor()
  assert.match(readFileSync(join(userData,'skills','testablauf.md'),'utf8'),/Ergebnis prüfen/)
  await app.evaluate(()=>globalThis.learningTest.proposeSkill({name:'Testablauf',description:'Verbesserter Ablauf',steps:'1. Neues Ergebnis prüfen.',source:'manual'}))
  await page.getByText('Vorschau ansehen',{exact:true}).click()
  assert.equal(await page.getByRole('heading',{name:'Bisher',exact:true}).count(),1)
  await app.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows().find(w=>w.webContents.getURL().includes('crystal.html')).setSize(1000,900))
  await page.screenshot({path:resolve('out/audit/self-improvement-ui.png')})
  await app.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows().find(w=>w.webContents.getURL().includes('crystal.html')).setSize(520,800))
  await page.screenshot({path:resolve('out/audit/self-improvement-ui-narrow.png')})
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false)
  const file=join(userData,'skills','testablauf.md')
  writeFileSync(file,readFileSync(file,'utf8').replace('Ergebnis prüfen','Zwischenzeitlich geändert'))
  await page.getByRole('button',{name:'Übernehmen',exact:true}).click()
  await page.getByRole('alert').filter({hasText:'inzwischen geändert'}).waitFor()
  assert.match(readFileSync(file,'utf8'),/Zwischenzeitlich geändert/)
  await page.getByRole('button',{name:'Verwerfen',exact:true}).click()
  assert.deepEqual(errors,[])
  console.log('PASS: proposal preview, reject without write, approve writes, previous version preview, narrow layout, no renderer errors')
 } finally { if(app)await app.close(); assert.ok(profile.startsWith(join(tmpdir(), 'james-learning-ui-'))); rmSync(profile, {recursive:true,force:true}) }
})().catch(e=>{console.error(e);process.exitCode=1})

